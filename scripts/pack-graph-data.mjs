#!/usr/bin/env node
/**
 * Compress + encrypt graph JSON into an opaque binary for public hosting.
 * This is obfuscation for casual network sniffing, not strong secrecy.
 */
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const candidates = [
  path.join(root, 'data', 'industry-graph.json'),
  path.join(root, 'public', 'industry-graph.json'),
];

const source = candidates.find((filePath) => fs.existsSync(filePath));
if (!source) {
  console.error('Missing industry-graph.json (expected in data/ or public/)');
  process.exit(1);
}

const raw = fs.readFileSync(source);
const gzipped = zlib.gzipSync(raw, { level: 9 });
const key = crypto.randomBytes(32);
const iv = crypto.randomBytes(12);
const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
const encrypted = Buffer.concat([cipher.update(gzipped), cipher.final()]);
const tag = cipher.getAuthTag();
const payload = Buffer.concat([iv, tag, encrypted]);

const assetsDir = path.join(root, 'public', 'assets');
fs.mkdirSync(assetsDir, { recursive: true });

// Remove previous packed blobs and any plaintext graph JSON from public/
for (const name of fs.readdirSync(assetsDir)) {
  if (name.startsWith('m.') && name.endsWith('.bin')) {
    fs.unlinkSync(path.join(assetsDir, name));
  }
}
const publicPlain = path.join(root, 'public', 'industry-graph.json');
if (fs.existsSync(publicPlain)) {
  const dataDir = path.join(root, 'data');
  fs.mkdirSync(dataDir, { recursive: true });
  const dataPlain = path.join(dataDir, 'industry-graph.json');
  if (!fs.existsSync(dataPlain)) {
    fs.renameSync(publicPlain, dataPlain);
  } else {
    fs.unlinkSync(publicPlain);
  }
}

const hash = crypto.createHash('sha256').update(payload).digest('hex').slice(0, 12);
const binName = `m.${hash}.bin`;
const binPath = path.join(assetsDir, binName);
fs.writeFileSync(binPath, payload);

const generatedDir = path.join(root, 'src', 'generated');
fs.mkdirSync(generatedDir, { recursive: true });
const metaPath = path.join(generatedDir, 'pack-meta.js');
fs.writeFileSync(
  metaPath,
  `/* generated by scripts/pack-graph-data.mjs — do not edit */\n` +
    `export const PACK_PATH = "assets/${binName}";\n` +
    `export const PACK_KEY = "${key.toString('base64')}";\n`
);

const dataDir = path.join(root, 'data');
fs.mkdirSync(dataDir, { recursive: true });
if (source !== path.join(dataDir, 'industry-graph.json')) {
  // keep a local plaintext copy for regeneration if we only had public/
  if (!fs.existsSync(path.join(dataDir, 'industry-graph.json'))) {
    fs.copyFileSync(source, path.join(dataDir, 'industry-graph.json'));
  }
}

console.log(
  `Packed ${path.relative(root, source)} -> public/assets/${binName} ` +
    `(${(raw.length / 1e6).toFixed(1)} MB -> ${(payload.length / 1e6).toFixed(1)} MB)`
);
